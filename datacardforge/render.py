def _chart_value(value) -> str:
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value)


def human_bytes(size: int) -> str:
    value = float(size)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if value < 1024 or unit == "TB":
            if unit == "B":
                return f"{int(value)} B"
            return f"{value:.1f} {unit}"
        value /= 1024
    return f"{size} B"


def bar_chart(title: str, rows: list[tuple[str, float]], *, maximum: float | None = None, suffix: str = "") -> str:
    if not rows:
        return "<p class=\"empty\">No chart.</p>"
    peak = maximum if maximum else max(value for _, value in rows)
    if peak <= 0:
        peak = 1
    width = 720
    label_w = 168
    bar_w = 390
    row_h = 28
    height = 36 + row_h * len(rows)
    parts = [
        f'<svg viewBox="0 0 {width} {height}" '
        f'role="img" aria-label="{_esc(title)}" width="100%">',
        f"<title>{_esc(title)}</title>",
    ]
    for index, (label, value) in enumerate(rows):
        y = 28 + index * row_h
        length = max(0.0, min(bar_w, bar_w * (value / peak)))
        color = _BAR_COLORS[index % len(_BAR_COLORS)]
        shown = _chart_value(value) + suffix
        short = label if len(label) <= 22 else label[:21] + "…"
        parts.append(
            f'<text x="0" y="{y}" font-size="13" fill="#1c2433">{_esc(short)}</text>'
            f'<rect x="{label_w}" y="{y - 12}" width="{length:.1f}" height="16" fill="{color}"></rect>'
            f'<text x="{label_w + bar_w + 10}" y="{y}" font-size="13" fill="#1c2433">{_esc(shown)}</text>'
        )
    parts.append("</svg>")
    return "".join(parts)


def _size_markdown(card: dict) -> str:
    size = card["size"]
    resolution = size["resolution"]
    rows = [
        ["Rows", size["rows"]],
        ["Columns", size["columns"]],
        ["Tables", size["tables"]],
        ["Files", size["files"]],
        ["Bytes on disk", f"{size['bytes']} ({human_bytes(size['bytes'])})"],
        ["Images", size["images"]],
    ]
    if size["images"]:
        rows.append(
            [
                "Resolution",
                (
                    f"{resolution['min_width']}–{resolution['max_width']} × "
                    f"{resolution['min_height']}–{resolution['max_height']} px, "
                    f"mean {resolution['mean_width']} × {resolution['mean_height']}, "
                    f"shortest side {resolution['min_side']} px, "
                    f"{resolution['small_image_count']} smaller than "
                    f"{resolution['small_image_threshold']} px"
                ),
            ]
        )
    if size.get("unreadable_images"):
        rows.append(["Unreadable images", size["unreadable_images"]])
    return _md_table(["Measure", "Value"], rows)


def _schema_markdown(card: dict) -> str:
    if not card["schema"]:
        return "_No tabular columns._"
    rows = [
        [
            column["table"],
            column["column"],
            column["dtype"],
            ", ".join(column["examples"]) or "—",
            column["unique_count"],
            column["null_count"],
        ]
        for column in card["schema"]
    ]
    return _md_table(["Table", "Column", "Type", "Examples", "Unique", "Nulls"], rows)


def _balance_markdown(card: dict) -> str:
    balance = card["class_balance"]
    if balance["total"] <= 0:
        return "_No label column or image classes found._"
    ratio = "n/a" if balance["imbalance_ratio"] is None else f"{balance['imbalance_ratio']:.3f}"
    lines = [
        f"Source: `{balance['source']}`. Total: {balance['total']}. Imbalance ratio (max/min): {ratio}.",
        "",
    ]
    if balance.get("unlabeled"):
        lines.append(f"Unlabeled rows: {balance['unlabeled']}.")
        lines.append("")
    lines.append(
        _md_table(
            ["Label", "Count", "Percent"],
            [[row["label"], row["count"], f"{row['percent']:.2f}"] for row in balance["counts"]],
        )
    )
    return "\n".join(lines)


def _missing_markdown(card: dict) -> str:
    missing = card["missingness"]
    if missing["rows"] <= 0:
        return "_No tabular rows._"
    lines = [
        (
            f"Rows with any missing value: {missing['rows_with_any_missing']} "
            f"of {missing['rows']} ({missing['rows_with_any_missing_percent']:.2f}%)."
        ),
        "",
        _md_table(
            ["Table", "Column", "Nulls", "Null %"],
            [
                [column["table"], column["column"], column["null_count"], f"{column['null_percent']:.2f}"]
                for column in missing["columns"]
            ],
        ),
    ]
    return "\n".join(lines)


def _dupes_markdown(card: dict) -> str:
    rows = card["duplicates"]["rows"]
    images = card["duplicates"]["images"]
    lines = [
        (
            f"Exact duplicate rows (copies beyond the first): {rows['extra_duplicate_rows']}. "
            f"Rows that sit in a duplicate group: {rows['rows_in_duplicate_groups']}. "
            f"Duplicate groups: {rows['duplicate_groups']}."
        ),
        "",
        (
            f"Exact duplicate images (extra files): {images['exact_extra_files']}. "
            f"Near-duplicate images (extra distinct files): {images['near_extra_files']}."
        ),
        "",
        images.get("method", ""),
    ]
    if images["exact_groups"]:
        lines += ["", "Exact image groups:", ""]
        for group in images["exact_groups"]:
            lines.append(f"- {group['count']} files, sha256 `{group['sha256'][:12]}…`")
            for path in group["paths"]:
                lines.append(f"  - `{path}`")
    if images["near_groups"]:
        lines += ["", "Near image groups:", ""]
        for group in images["near_groups"]:
            lines.append(
                f"- {group['distinct_files']} distinct files "
                f"(max Hamming {group['max_hamming']}, max color MAE {group['max_color_mae']})"
            )
            for path in group["paths"]:
                lines.append(f"  - `{path}`")
    if not rows["extra_duplicate_rows"] and not images["exact_groups"] and not images["near_groups"]:
        lines += ["", "_No exact or near duplicates found._"]
    return "\n".join(lines)


def _sources_markdown(card: dict) -> str:
    lines = []
    autos = card["sources"]["auto"]
    users = card["sources"]["user"]
    if not autos and not users:
        return "_No README, LICENSE, or source.txt found, and no notes added._"
    if autos:
        lines.append("Found with the dataset:")
        lines.append("")
        for item in autos:
            lines.append(f"- `{item['path']}` ({item['kind']}): {item['excerpt'] or '_(empty)_'}")
    if users:
        lines += ["", "Notes:", ""]
        for item in users:
            lines.append(f"- {item['text']}")
    return "\n".join(lines)


def _license_markdown(card: dict) -> str:
    license_info = card["license"]
    detected = license_info.get("detected_from") or "nothing"
    return (
        f"SPDX: `{license_info['value']}` ({license_info['source']}). "
        f"Scan of {detected} suggested `{license_info['auto_value']}`."
    )


def _gaps_markdown(card: dict) -> str:
    lines = []
    autos = card["known_gaps"]["auto"]
    if autos:
        lines.append("Suggested from the scan:")
        lines.append("")
        for item in autos:
            lines.append(f"- {item}")
    else:
        lines.append("_No gaps suggested from the scan._")
    lines += ["", "Notes:", "", _quote(card["known_gaps"]["user"])]
    return "\n".join(lines)


def _pii_markdown(card: dict) -> str:
    if not card["pii_hints"]:
        return "_No columns looked like emails, phone numbers, or personal names._"
    return _md_table(
        ["Table", "Column", "Hint", "Match %", "Why"],
        [
            [
                hint["table"],
                hint["column"],
                hint["kind"],
                f"{hint['match_percent']:.2f}",
                hint["reason"],
            ]
            for hint in card["pii_hints"]
        ],
    )


def _html_overview(card: dict) -> str:
    overview = card["overview"]
    rows = "".join(
        f"<tr><th>{label}</th><td>{_esc(field['value']) or '<span class=\"empty\">Not set</span>'}"
        f" <span class=\"note\">({_esc(field['source'])})</span></td></tr>"
        for label, field in (
            ("Name", overview["name"]),
            ("Version", overview["version"]),
            ("Created", overview["created"]),
            ("Description", overview["description"]),
        )
    )
    return f'<section><h2 id="overview">Overview</h2><table>{rows}</table></section>'


def _html_size(card: dict) -> str:
    size = card["size"]
    tiles = [
        ("Rows", size["rows"]),
        ("Columns", size["columns"]),
        ("Files", size["files"]),
        ("On disk", human_bytes(size["bytes"])),
        ("Images", size["images"]),
        ("Tables", size["tables"]),
    ]
    blocks = "".join(f"<div class=\"tile\"><span>{_esc(label)}</span><strong>{_esc(value)}</strong></div>" for label, value in tiles)
    extra = ""
    resolution = size["resolution"]
    if size["images"]:
        extra = (
            "<p>Resolution "
            f"{resolution['min_width']}–{resolution['max_width']} wide, "
            f"{resolution['min_height']}–{resolution['max_height']} tall, "
            f"mean {resolution['mean_width']} × {resolution['mean_height']} px. "
            f"Shortest side {resolution['min_side']} px. "
            f"{resolution['small_image_count']} image(s) under "
            f"{resolution['small_image_threshold']} px.</p>"
        )
    return f'<section><h2 id="size">Size</h2><div class="tiles">{blocks}</div>{extra}</section>'


def _html_schema(card: dict) -> str:
    if not card["schema"]:
        body = '<p class="empty">This dataset has no tabular columns.</p>'
    else:
        body_rows = "".join(
            "<tr>"
            f"<td>{_esc(column['table'])}</td>"
            f"<td>{_esc(column['column'])}</td>"
            f"<td>{_esc(column['dtype'])}</td>"
            f"<td>{_esc(', '.join(column['examples']) or '—')}</td>"
            f"<td>{column['unique_count']}</td>"
            f"<td>{column['null_count']}</td>"
            "</tr>"
            for column in card["schema"]
        )
        body = (
            "<table><thead><tr><th>Table</th><th>Column</th><th>Type</th>"
            f"<th>Examples</th><th>Unique</th><th>Nulls</th></tr></thead><tbody>{body_rows}</tbody></table>"
        )
    return f'<section><h2 id="schema">Schema</h2>{body}</section>'


def _html_balance(card: dict) -> str:
    balance = card["class_balance"]
    if balance["total"] <= 0:
        body = '<p class="empty">No label column or image classes found.</p>'
    else:
        ratio = "n/a" if balance["imbalance_ratio"] is None else f"{balance['imbalance_ratio']:.3f}"
        chart = bar_chart(
            "Class balance",
            [(row["label"], float(row["count"])) for row in balance["counts"]],
        )
        table_rows = "".join(
            f"<tr><td>{_esc(row['label'])}</td><td>{row['count']}</td><td>{row['percent']:.2f}</td></tr>"
            for row in balance["counts"]
        )
        unlabeled = (
            f"<p class=\"note\">Unlabeled rows: {balance['unlabeled']}.</p>" if balance.get("unlabeled") else ""
        )
        body = (
            f"<p>Source <code>{_esc(balance['source'])}</code>. "
            f"Total {balance['total']}. Imbalance ratio {ratio}.</p>"
            f"{unlabeled}{chart}"
            "<table><thead><tr><th>Label</th><th>Count</th><th>Percent</th></tr></thead>"
            f"<tbody>{table_rows}</tbody></table>"
        )
    extra = ""
    image_counts = balance.get("image_counts") or []
    if image_counts:
        extra_rows = "".join(
            f"<tr><td>{_esc(row['label'])}</td><td>{row['count']}</td><td>{row['percent']:.2f}</td></tr>"
            for row in image_counts
        )
        extra = (
            "<h3>Image folders</h3><table><thead><tr><th>Class</th><th>Count</th><th>Percent</th></tr></thead>"
            f"<tbody>{extra_rows}</tbody></table>"
        )
    return f'<section><h2 id="class-balance">Class balance</h2>{body}{extra}</section>'


def _html_missing(card: dict) -> str:
    missing = card["missingness"]
    if missing["rows"] <= 0:
        body = '<p class="empty">No tabular rows.</p>'
    else:
        chart = bar_chart(
            "Missing values by column",
            [(f"{column['column']}", float(column["null_percent"])) for column in missing["columns"]],
            maximum=100,
            suffix="%",
        )
        table_rows = "".join(
            "<tr>"
            f"<td>{_esc(column['table'])}</td><td>{_esc(column['column'])}</td>"
            f"<td>{column['null_count']}</td><td>{column['null_percent']:.2f}</td></tr>"
            for column in missing["columns"]
        )
        body = (
            f"<p>Rows with any missing value: {missing['rows_with_any_missing']} "
            f"of {missing['rows']} ({missing['rows_with_any_missing_percent']:.2f}%).</p>"
            f"{chart}"
            "<table><thead><tr><th>Table</th><th>Column</th><th>Nulls</th><th>Null %</th></tr></thead>"
            f"<tbody>{table_rows}</tbody></table>"
        )
    return f'<section><h2 id="missingness">Missingness</h2>{body}</section>'


def _html_dupes(card: dict) -> str:
    rows = card["duplicates"]["rows"]
    images = card["duplicates"]["images"]
    exact = "".join(
        f"<li>{group['count']} files <code>{_esc(group['sha256'][:12])}…</code>"
        f"<ul>{''.join(f'<li><code>{_esc(path)}</code></li>' for path in group['paths'])}</ul></li>"
        for group in images["exact_groups"]
    )
    near = "".join(
        "<li>"
        f"{group['distinct_files']} distinct files, max Hamming {group['max_hamming']}, "
        f"max color MAE {group['max_color_mae']}"
        f"<ul>{''.join(f'<li><code>{_esc(path)}</code></li>' for path in group['paths'])}</ul></li>"
        for group in images["near_groups"]
    )
    exact_html = f"<ul>{exact}</ul>" if exact else "<p class=\"empty\">No exact image copies.</p>"
    near_html = f"<ul>{near}</ul>" if near else "<p class=\"empty\">No near-duplicate images.</p>"
    body = (
        f"<p>Exact duplicate rows (copies beyond the first): <strong>{rows['extra_duplicate_rows']}</strong>. "
        f"Rows in a duplicate group: {rows['rows_in_duplicate_groups']}. "
        f"Groups: {rows['duplicate_groups']}.</p>"
        f"<p>Exact extra image files: <strong>{images['exact_extra_files']}</strong>. "
        f"Near-duplicate extra files: <strong>{images['near_extra_files']}</strong>. "
        f"Compared {images['compared']} image(s)"
        + (f", {images['unreadable']} unreadable." if images.get("unreadable") else ".")
        + "</p>"
        f"<p class=\"note\">{_esc(images.get('method', ''))}</p>"
        f"<h3>Exact image groups</h3>{exact_html}"
        f"<h3>Near image groups</h3>{near_html}"
    )
    return f'<section><h2 id="duplicates">Duplicates</h2>{body}</section>'


def _html_sources(card: dict) -> str:
    autos = card["sources"]["auto"]
    users = card["sources"]["user"]
    if not autos and not users:
        body = '<p class="empty">No README, LICENSE, or source.txt found, and no notes added.</p>'
    else:
        found = "".join(
            f"<li><code>{_esc(item['path'])}</code> ({_esc(item['kind'])}): {_esc(item['excerpt'] or 'empty')}</li>"
            for item in autos
        )
        notes = "".join(f"<li>{_esc(item['text'])}</li>" for item in users)
        body = ""
        if found:
            body += f"<p>Found with the dataset:</p><ul>{found}</ul>"
        if notes:
            body += f"<p>Notes:</p><ul>{notes}</ul>"
    return f'<section><h2 id="sources">Sources</h2>{body}</section>'


def _html_license(card: dict) -> str:
    info = card["license"]
    detected = info.get("detected_from") or "nothing"
    body = (
        f"<p>SPDX <strong>{_esc(info['value'])}</strong> "
        f"<span class=\"note\">({_esc(info['source'])})</span>. "
        f"Scan of {_esc(detected)} suggested <code>{_esc(info['auto_value'])}</code>.</p>"
    )
    return f'<section><h2 id="license">License</h2>{body}</section>'


