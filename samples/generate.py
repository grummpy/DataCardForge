"""Write the synthetic sample datasets. No real personal data."""

from __future__ import annotations

import csv
import shutil
from pathlib import Path

import pyarrow as pa
import pyarrow.parquet as pq
from PIL import Image, ImageDraw

BG = (14, 18, 42)
CIRCLE_SIZE = 128
SQUARE_SIZE = 96
TINY_SIZE = 16

NAMES = (
    ("Rowan", "Kepler"),
    ("Mina", "Quill"),
    ("Theo", "Byte"),
    ("Nia", "Forge"),
    ("Sol", "Harper"),
    ("Willa", "North"),
    ("Idris", "Vale"),
    ("Pilar", "Moss"),
)


def main() -> None:
    root = Path(__file__).resolve().parent
    write_csv_dataset(root / "colored-shapes-csv")
    write_parquet_dataset(root / "colored-shapes-parquet")
    write_image_dataset(root / "colored-shapes-images")
    print(f"Wrote synthetic samples under {root}")


def shift(color: tuple[int, int, int], delta: int) -> tuple[int, int, int]:
    return tuple(max(0, min(255, channel + delta)) for channel in color)


def draw_circle(fill: tuple[int, int, int], size: int = CIRCLE_SIZE, delta: int = 0) -> Image.Image:
    image = Image.new("RGB", (size, size), BG)
    draw = ImageDraw.Draw(image)
    color = shift(fill, delta)
    margin = size // 6
    draw.ellipse((margin, margin, size - margin - 1, size - margin - 1), fill=color)
    highlight = max(4, size // 5)
    draw.ellipse((margin, margin, margin + highlight, margin + highlight), fill=shift(color, 36))
    return image


def draw_square(fill: tuple[int, int, int], size: int = SQUARE_SIZE) -> Image.Image:
    image = Image.new("RGB", (size, size), BG)
    draw = ImageDraw.Draw(image)
    margin = size // 5
    draw.rectangle((margin, margin, size - margin - 1, size - margin - 1), fill=fill)
    return image


def draw_triangle(fill: tuple[int, int, int], size: int = CIRCLE_SIZE) -> Image.Image:
    image = Image.new("RGB", (size, size), BG)
    draw = ImageDraw.Draw(image)
    margin = size // 6
    draw.polygon(
        [(size // 2, margin), (size - margin, size - margin), (margin, size - margin)],
        fill=fill,
    )
    return image


def draw_tiny() -> Image.Image:
    image = Image.new("RGB", (TINY_SIZE, TINY_SIZE), BG)
    draw = ImageDraw.Draw(image)
    draw.rectangle((1, 12, 14, 14), fill=(80, 220, 120))
    return image


def save_jpeg(image: Image.Image, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, "JPEG", quality=95, subsampling=0)


def brighten_file(source: Path, dest: Path, amount: int = 12) -> None:
    with Image.open(source) as image:
        rgb = image.convert("RGB")
        pixels = rgb.load()
        width, height = rgb.size
        for y in range(height):
            for x in range(width):
                red, green, blue = pixels[x, y]
                pixels[x, y] = (min(255, red + amount), min(255, green + amount), min(255, blue + amount))
        save_jpeg(rgb, dest)


def write_csv_dataset(folder: Path) -> None:
    folder.mkdir(parents=True, exist_ok=True)
    labels = ["circle"] * 16 + ["square"] * 8 + ["triangle"]
    rows = []
    for index, label in enumerate(labels, start=1):
        first, last = NAMES[(index - 1) % len(NAMES)]
        width = "" if index == 4 else str([64, 48, 96, 32, 80][index % 5])
        email = "" if index in {8, 20} else f"{first.lower()}@example.com"
        phone = "" if index in {8, 15} else f"555-{index:04d}"
        person = "" if index == 12 else f"{first} {last}"
        notes = "" if index % 3 == 0 else "synthetic row"
        rows.append([f"s{index:03d}", width, label, email, phone, person, notes])
    rows.append(list(rows[0]))
    rows.append(list(rows[2]))
    path = folder / "measurements.csv"
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(
            ["sample_id", "width_px", "label", "contact_email", "phone", "person_name", "notes"]
        )
        writer.writerows(rows)
    (folder / "README.md").write_text(
        "# Colored shapes (synthetic)\n\n"
        "Toy measurements of colored geometric shapes for a local data-card demo. "
        "Every name, email, and phone number is fictional, and every address uses example.com.\n",
        encoding="utf-8",
    )
    (folder / "LICENSE").write_text(
        "MIT License\n\n"
        "Copyright (c) 2026 Synthetic Data Lab\n\n"
        "Permission is hereby granted, free of charge, to any person obtaining a copy "
        "of this dataset to use it for local software tests.\n\n"
        "THE DATA IS SYNTHETIC AND PROVIDED AS IS.\n",
        encoding="utf-8",
    )
    (folder / "source.txt").write_text(
        "Generated by samples/generate.py inside DataCardForge. Synthetic only. "
        "No personal data and no secrets.\n",
        encoding="utf-8",
    )


def write_parquet_dataset(folder: Path) -> None:
    folder.mkdir(parents=True, exist_ok=True)
    rows = []
    for index in range(1, 9):
        rows.append(
            {
                "sample_id": f"p{index:02d}",
                "score": index / 10,
                "class": "circle",
                "notes": None if index % 4 == 0 else "synthetic",
            }
        )
    rows.append(dict(rows[0]))
    for index, label in enumerate(("square", "square", "square", "triangle"), start=1):
        rows.append(
            {
                "sample_id": f"q{index}",
                "score": None if index == 2 else round(0.3 * index, 2),
                "class": label,
                "notes": "synthetic",
            }
        )
    schema = pa.schema(
        [
            ("sample_id", pa.string()),
            ("score", pa.float64()),
            ("class", pa.string()),
            ("notes", pa.string()),
        ]
    )
    table = pa.Table.from_pylist(rows, schema=schema)
    pq.write_table(table, folder / "measurements.parquet")
    (folder / "README.md").write_text(
        "# Colored shapes parquet (synthetic)\n\n"
        "A small Parquet twin of the shape measurements, still entirely fictional.\n",
        encoding="utf-8",
    )
    (folder / "LICENSE").write_text(
        "Apache License\n"
        "Version 2.0, January 2004\n\n"
        "Synthetic dataset for local tests. No real personal data.\n",
        encoding="utf-8",
    )


def write_image_dataset(folder: Path) -> None:
    if folder.exists():
        shutil.rmtree(folder)
    colors = {
        "crimson": (180, 48, 42),
        "cobalt": (46, 92, 210),
        "gold": (214, 164, 42),
        "mint": (36, 168, 132),
        "violet": (124, 64, 196),
    }
    crimson = folder / "circle" / "crimson.jpg"
    save_jpeg(draw_circle(colors["crimson"]), crimson)
    shutil.copyfile(crimson, folder / "circle" / "crimson_copy.jpg")
    brighten_file(crimson, folder / "circle" / "crimson_near.jpg", 12)
    for name in ("cobalt", "gold", "mint", "violet"):
        save_jpeg(draw_circle(colors[name]), folder / "circle" / f"{name}.jpg")
    save_jpeg(draw_square((214, 140, 48)), folder / "square" / "amber.jpg")
    save_jpeg(draw_square((70, 78, 190)), folder / "square" / "indigo.jpg")
    save_jpeg(draw_tiny(), folder / "square" / "tiny.jpg")
    save_jpeg(draw_triangle((36, 170, 120)), folder / "triangle" / "sea.jpg")
    (folder / "README.md").write_text(
        "# Colored shape images (synthetic)\n\n"
        "Class folders of drawn shapes. One file is an exact copy and one is a slightly "
        "brighter near-copy. A 16 pixel image is included on purpose.\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
